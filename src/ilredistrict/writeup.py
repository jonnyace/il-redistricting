"""Build results/REPORT.md from the metrics files, so the report is a pure
function of the results (no hand-typed numbers)."""
from __future__ import annotations

import json

from .fetch import load_sources
from .report import RESULTS

ROWS = [
    ("Population: largest district over ideal (%)", "population_max_over_pct"),
    ("Population: largest district under ideal (%)", "population_max_under_pct"),
    ("Population: total range, max minus min (%)", "population_range_pct"),
    ("Counties split (of 102)", "county_units_split"),
    ("County extra pieces", "county_extra_pieces"),
    ("Municipalities split (of 1,298 with people)", "municipality_units_split"),
    ("Municipality extra pieces", "municipality_extra_pieces"),
    ("Townships split (of 1,427 with people)", "township_units_split"),
    ("Township extra pieces", "township_extra_pieces"),
    ("Total interior district border (km)", "interior_border_km"),
    ("Polsby-Popper compactness, mean (1 = circle)", "polsby_popper_mean"),
    ("Polsby-Popper compactness, worst district", "polsby_popper_min"),
    ("R-leaning seats (avg margin R+5 or more)", "seats_R"),
    ("Toss-up seats (avg margin within 5 pts)", "seats_toss-up"),
    ("D-leaning seats (avg margin D+5 or more)", "seats_D"),
    ("Seats Quinn (D) carried, 2014 Governor", "seats_won_D_gov2014"),
    ("Seats Pritzker (D) carried, 2018 Governor", "seats_won_D_gov2018"),
    ("Seats Pritzker (D) carried, 2022 Governor", "seats_won_D_gov2022"),
    ("VRA screen: Hispanic majority of voting-age pop", "vra_screen_hispanic_majority_vap"),
    ("VRA screen: Black (non-Hispanic, alone) majority of VAP", "vra_screen_black_majority_vap"),
    ("VRA screen: all minority groups combined majority of VAP", "vra_screen_minority_majority_vap"),
]


def _load(name):
    path = RESULTS / name / "metrics.json"
    return json.loads(path.read_text()) if path.exists() else None


def write_report() -> None:
    plans = [(n, _load(n)) for n in ("enacted", "hjrca41", "weaver")]
    plans = [(n, m) for n, m in plans if m]
    head = {"enacted": "Enacted 2021 map", "hjrca41": "HJRCA 41 mode", "weaver": "Weaver mode"}
    lines = ["# Results", "",
             "Generated by `python -m ilredistrict run`. Every number below is read from "
             "`results/*/metrics.json`; nothing is typed by hand.", "",
             "| Measure | " + " | ".join(head[n] for n, _ in plans) + " |",
             "|---|" + "---|" * len(plans)]
    for label, key in ROWS:
        lines.append(f"| {label} | " + " | ".join(str(m["summary"].get(key, "")) for _, m in plans) + " |")
    lines += ["", "## Run details", ""]
    for n, m in plans:
        if n == "enacted":
            continue
        s = m["search"]
        lines.append(f"* **{head[n]}**: seed {m['seed']}, {m['params']['search']['steps']:,} annealing steps, "
                     f"{s['total_seconds']:,.0f} s on one CPU core (Python {m['python']}). "
                     f"Moves accepted: {s['recom_accepted']:,} of {s['recom_tried']:,} recombinations, "
                     f"{s['flip_accepted']:,} of {s['flip_tried']:,} single-precinct flips. "
                     f"Senate: {m['summary']['senate_nesting']}.")
        if n == "weaver":
            t = m["weaver_target_seats"]
            lines.append(f"  Target was {t['R']} R-leaning, {t['toss-up']} toss-up, {t['D']} D-leaning "
                         f"(30% / 32% / 38% of 118, Rep. Weaver's example).")
    lines += ["", "Runtime varies by machine. The map does not: same seed, same data, same "
              "package versions give the same `assignment_vtd.csv`.", "",
              "## Input files (SHA-256 re-checked at the start of every run)", ""]
    for k, v in load_sources().items():
        lines.append(f"* `{v['file']}`: {v['desc']} <{v['url']}> sha256 `{v['sha256']}`")
    (RESULTS / "REPORT.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {RESULTS / 'REPORT.md'}")
